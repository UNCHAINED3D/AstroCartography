def _norm(value: str) -> str:
    return " ".join((value or "").strip().lower().split())


# Normalized lookup index so "berlin"/"Germany" resolves the same as "Berlin"/"Germany".
_ALIASES: dict[str, str] = {
    "nyc": "New York",
    "new york city": "New York",
    "bali": "Bali (Ubud)",
    "ubud": "Bali (Ubud)",
    "cascais": "Lisbon Coast (Cascais)",
    "lisbon coast": "Lisbon Coast (Cascais)",
    "mexico city df": "Mexico City",
    "cdmx": "Mexico City",
    "sao paulo": "São Paulo",
}

_NORMALIZED_PROFILES: dict[tuple[str, str], dict[str, Any]] = {
    (_norm(city), _norm(country)): profile
    for (city, country), profile in _PLACE_PROFILES.items()
}


def _resolve(city_name: str, country: str) -> tuple[str, str]:
    city = _norm(city_name)
    city = _norm(_ALIASES.get(city, city))
    return city, _norm(country)


def get_place_profile(city_name: str = "", country: str = "", region: str = "") -> dict[str, Any]:
    key = _resolve(city_name, country)
    profile = dict(_NORMALIZED_PROFILES.get(key, _GENERIC_PROFILE))
    profile["city"] = city_name or "This place"
    profile["country"] = country
    if region and not profile.get("region"):
        profile["region"] = region
    return profile